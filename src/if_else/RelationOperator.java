package if_else;

public class RelationOperator {
    static void main(String[] args) {
        System.out.println(5 > 3);
        System.out.println(5 < 3);
        System.out.println(5 == 5);
        System.out.println(5 != 3);
        System.out.println(6 >= 7);
        System.out.println(6 <= 7);

    }
}
