package Basic;

public class IncrementDecrement {
    static void main(String[] args) {
            int x = 10 ;
            System.out.println(x);
            x += 6;
            System.out.println(x);
            x -= 6;
            System.out.println(x);
            x *= 6;
            System.out.println(x);
            x ++;
            System.out.println(x);
            ++x;
            System.out.println(x);
            x--;
            System.out.println(x);
            --x;
            System.out.println(x);

        }
    }
